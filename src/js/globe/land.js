export function lngLatToUv(lng, lat, width, height) {
  return [((lng + 180) / 360) * width, ((90 - lat) / 180) * height];
}

export function drawLand(ctx, width, height, fill, stroke) {
  ctx.beginPath();
  for (const ring of LAND_POLYGONS) {
    ring.forEach(([lng, lat], i) => {
      const [x, y] = lngLatToUv(lng, lat, width, height);
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    });
    ctx.closePath();
  }
  if (fill) {
    ctx.fillStyle = fill;
    ctx.fill();
  }
  if (stroke) {
    ctx.strokeStyle = stroke;
    ctx.lineWidth = 1.1;
    ctx.stroke();
  }
}
